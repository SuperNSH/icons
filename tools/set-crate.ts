// The files of one set's crate, as text. Pure functions, so tests need no network.
import { rustString, rustViewBox } from "../cli/generate.ts";
import { type Resolved, rustConst, tsName } from "../tsx/iconify.ts";

export interface SetMeta {
  prefix: string;
  name: string;
  license: string;
  licenseUrl: string;
  author: string;
  authorUrl: string;
  multicolor: boolean;
}

export const crateName = (prefix: string) => `supernsh-icons-${prefix}`;

/** Each icon's TS export. Two names can become one (`a-1` and `a1`): a name the set has exported
 * before keeps its export, and a newcomer that clashes gets its name spelled out (`bxA_1`). */
export function tsNames(prefix: string, icons: Resolved[], before: Map<string, string>): Map<string, string> {
  const out = new Map<string, string>();
  const taken = new Set<string>();
  const claim = (name: string, ident: string) => {
    if (taken.has(ident)) throw new Error(`${prefix}: \`${name}\` becomes \`${ident}\`, which is taken`);
    taken.add(ident);
    out.set(name, ident);
  };
  for (const { name } of icons) if (before.has(name)) claim(name, before.get(name)!);
  for (const { name } of icons) {
    if (out.has(name)) continue;
    const ident = tsName(prefix, name);
    claim(name, taken.has(ident) ? `${tsName(prefix, "")}_${name.replace(/[^a-zA-Z0-9]/g, "_")}` : ident);
  }
  return out;
}

/** `tsx/index.ts`: one export per icon, one line each, so a data update diffs by icon. */
export function tsModule(set: SetMeta, icons: Resolved[], names: Map<string, string>): string {
  const lines = icons.map(
    (i) => `export const ${names.get(i.name)}: IconData = ${JSON.stringify({ set: set.prefix, name: i.name, body: i.body, viewBox: i.viewBox, multicolor: set.multicolor })};`,
  );
  return `// ${set.name} (${set.license}), by ${set.author}. Generated by tools/fetch-data.ts: do not edit.
import type { IconData } from "supernsh-icons";

${lines.join("\n")}
`;
}

/** `src/icons.rs`: a constant per icon, and `set::INFO` and `set::ALL` (sorted, for `supernsh_icons::find`). */
export function rustModule(set: SetMeta, icons: Resolved[]): string {
  const seen = new Map<string, string>();
  for (const { name } of icons) {
    const ident = rustConst(name);
    const first = seen.get(ident);
    if (first !== undefined) throw new Error(`${set.prefix}: \`${first}\` and \`${name}\` both become \`${ident}\``);
    seen.set(ident, name);
  }
  const lines = icons.map(
    (i) =>
      `pub const ${rustConst(i.name)}: Icon = Icon { set: ${rustString(set.prefix)}, name: ${rustString(i.name)}, body: ${rustString(i.body)}, view_box: ${rustViewBox(i.viewBox)}, multicolor: ${set.multicolor} };`,
  );
  // A module, not constants beside the icons: an icon named `all` is a constant too.
  return `// Generated by tools/fetch-data.ts: do not edit.
use supernsh_icons::Icon;

${lines.join("\n")}

/// The set's info and its icons, sorted by name.
pub mod set {
    use supernsh_icons::{Icon, IconSet};
    pub const INFO: IconSet = IconSet { prefix: ${rustString(set.prefix)}, name: ${rustString(set.name)}, license: ${rustString(set.license)}, author: ${rustString(set.author)}, multicolor: ${set.multicolor}, total: ${icons.length} };
    pub const ALL: &[Icon] = &[${icons.map((i) => `super::${rustConst(i.name)}`).join(", ")}];
}
`;
}

export function cargoToml(set: SetMeta): string {
  return `[package]
name = "${crateName(set.prefix)}"
description = ${JSON.stringify(`${set.name} icons for Native Shell (NSH) apps, in Rust and TSX, drawn by supernsh-icons`)}
version.workspace = true
edition.workspace = true
license = "${set.license}"
repository.workspace = true
authors.workspace = true
keywords = ["nshm", "nsh", "icons", "iconify", "svg"]
include = ["/Cargo.toml", "/NOTICE.md", "/nsh.json", "/src/**", "/tsx/**"]

[dependencies]
nsh-core.workspace = true
supernsh-icons.workspace = true
`;
}

export function nshJson(set: SetMeta, version: string): string {
  const name = crateName(set.prefix);
  return `${JSON.stringify({ nsh: ">=0.7.1", exports: { [name]: "tsx/index.ts" }, dependencies: { "supernsh-icons": `^${version}` } }, null, 2)}\n`;
}

export function libRs(set: SetMeta): string {
  const krate = crateName(set.prefix).replaceAll("-", "_");
  return `//! ${set.name} (${set.license}) for Native Shell apps, in Rust and TSX: a constant per
//! icon, drawn with \`supernsh_icons::icon\`. Only the icons an app names reach its binary.
//! Generated by tools/fetch-data.ts: do not edit.

#[rustfmt::skip]
mod icons;

pub use icons::*;

use nsh_core::prelude::{Registry, native_module};

/// The icons reach TSX as TSX (\`tsx/index.ts\`); this module exports nothing
/// and makes \`${krate}\` an nshm.
#[native_module("${crateName(set.prefix)}/native")]
fn native(_registry: &mut Registry) {}
`;
}

/** One set's line in the repository's NOTICE.md, and its crate's whole NOTICE.md. */
export function noticeLine(set: SetMeta): string {
  return `- **${set.name}** (\`${set.prefix}\`) by ${set.author || "unknown"}${set.authorUrl ? ` <${set.authorUrl}>` : ""}: ${set.license}${set.licenseUrl ? ` <${set.licenseUrl}>` : ""}`;
}

export function notice(set: SetMeta): string {
  return `# Notice

The icons in this crate are not ours. An app that ships them must follow their license, including attribution where it asks for it.

${noticeLine(set)}
`;
}
