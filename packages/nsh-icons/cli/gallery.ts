// What `supernsh-icons gallery` writes: the icon explorer demo's data. The set
// index (names, licenses, samples) is committed and powers search; each set's
// bodies go in their own module, loaded on demand, and are gitignored because
// together they are tens of megabytes. Pure functions, so tests need no data.
import { type IconifySet, resolveName } from "../src/iconify.ts";
import type { IconData } from "../src/markup.ts";
import type { ManifestEntry } from "./sources.ts";

/** The icons the demo's font showcase holds, all filled Phosphor shapes. */
export const DEMO_FONT_IDS = ["ph:gear-fill", "ph:heart-fill", "ph:house-fill", "ph:star-fill"];

/** A set's whole contribution to the demo, gathered by the command. */
export interface DemoSet {
  entry: ManifestEntry;
  /** Every icon and alias name, sorted; the bodies share this order. */
  names: string[];
  /** A few icons, drawn before the set's data has loaded. */
  sampleIcons: IconData[];
}

/** Up to six of the set's own samples, or its first icons when it lists none. */
export function demoSet(entry: ManifestEntry, set: IconifySet, names: string[]): DemoSet {
  const listed = set.info?.samples?.filter((name) => resolveName(set, name)) ?? [];
  const picked = (listed.length ? listed : names).slice(0, 6);
  return {
    entry,
    names,
    sampleIcons: picked.map((name) => {
      const icon = resolveName(set, name)!;
      return { set: set.prefix, name, body: icon.body, viewBox: icon.viewBox, multicolor: entry.multicolor };
    }),
  };
}

/** `src/demo-index.ts`: the metadata, names and samples of every set. */
export function demoIndex(sets: DemoSet[], version: string): string {
  const entries = sets.map((set) => `  {
    prefix: ${JSON.stringify(set.entry.prefix)},
    name: ${JSON.stringify(set.entry.name)},
    license: ${JSON.stringify(set.entry.license)},
    licenseUrl: ${JSON.stringify(set.entry.licenseUrl)},
    restrictive: ${set.entry.restrictive},
    multicolor: ${set.entry.multicolor},
    names: ${jsonLiteral(set.names)},
    samples: [
      ${set.sampleIcons.map((icon) => JSON.stringify(icon)).join(",\n      ")}
    ],
  }`);
  return `// Generated by \`supernsh-icons gallery\` from @iconify/json ${version}. The CLI
// rewrites this file; every icon keeps its set's license. The names power
// search; each set's bodies load on demand from ./data/, in this order.
import type { IconData } from "supernsh-icons";

export interface DemoSet {
  prefix: string;
  name: string;
  license: string;
  licenseUrl: string;
  /** The license asks for attribution, or limits commercial use. */
  restrictive: boolean;
  /** The set's icons keep their own colors; a tint does not apply. */
  multicolor: boolean;
  /** Every icon and alias name, sorted. \`data/<prefix>.ts\` holds the bodies. */
  names: string[];
  /** A few icons, drawn before the set's data has loaded. */
  samples: IconData[];
}

/** The @iconify/json release the bundled sets came from. */
export const VERSION = ${JSON.stringify(version)};

export const SETS: DemoSet[] = [
${entries.join(",\n")}
];
`;
}

/** A value as a `JSON.parse` of one string literal: the engine builds it in
 * a native pass instead of parsing tens of thousands of literals one by one. */
function jsonLiteral(value: unknown): string {
  return `JSON.parse(${JSON.stringify(JSON.stringify(value))})`;
}

/** `src/data/<prefix>.ts`: the bodies of a set's names, in that order. */
export function dataModule(prefix: string, setName: string, license: string, version: string, bodies: Array<[string, [number, number, number, number]]>): string {
  return `// Generated by \`supernsh-icons gallery\` from @iconify/json ${version} (${prefix}:
// ${setName}, ${license}). The bodies of demo-index.ts's names, in its order.
export const BODIES: Array<[body: string, viewBox: [number, number, number, number]]> = ${jsonLiteral(bodies)};
`;
}

/** `src/data/index.ts`: each set's bodies, one import away. */
export function dataIndex(prefixes: string[]): string {
  const entries = prefixes.map((prefix) => `  ${JSON.stringify(prefix)}: () => import(${JSON.stringify(`./${prefix}`)}),`);
  return `// Generated by \`supernsh-icons gallery\`: a set's bodies load when it is opened,
// so the demo starts with only the index and grows as you browse.
export const LAZY: Record<string, () => Promise<{ BODIES: Array<[string, [number, number, number, number]]> }>> = {
${entries.join("\n")}
};
`;
}
