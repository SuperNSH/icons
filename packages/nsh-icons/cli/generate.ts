// What the CLI writes: icon modules (TS or Rust) and icon fonts with their
// glyph maps. Pure functions over resolved icons, so tests need no network.
import { Readable } from "node:stream";
import { type IconifySet, resolveName, rustName, tsName } from "../src/iconify.ts";
import { svgMarkup } from "../src/markup.ts";

export type Lang = "ts" | "rust";

/** An icon picked by id, resolved, with where its set came from. */
export interface Picked {
  id: string;
  set: string;
  name: string;
  body: string;
  viewBox: [number, number, number, number];
  multicolor: boolean;
  setName: string;
  license: string;
  source: string;
}

/** `set:name` split, or an error naming the bad id. */
export function parseId(id: string): [string, string] {
  const at = id.indexOf(":");
  if (at <= 0 || at === id.length - 1) throw new Error(`\`${id}\` is not an icon id; write it as set:name, such as lucide:heart`);
  return [id.slice(0, at), id.slice(at + 1)];
}

/** Resolves `name` in a loaded set, with the set's info for the comments. */
export function pick(set: IconifySet, name: string, source: string): Picked {
  const resolved = resolveName(set, name);
  if (!resolved) throw new Error(`${set.prefix} has no icon \`${name}\``);
  return {
    id: `${set.prefix}:${name}`,
    set: set.prefix,
    name,
    body: resolved.body,
    viewBox: resolved.viewBox,
    multicolor: set.info?.palette === true,
    setName: set.info?.name ?? set.prefix,
    license: set.info?.license?.spdx ?? set.info?.license?.title ?? "unknown",
    source,
  };
}

/** The ids a generated file lists on its `// nsh-icons:` line. */
export function idsIn(text: string): string[] {
  const line = text.split("\n").find((l) => l.startsWith("// nsh-icons:"));
  return line ? line.slice("// nsh-icons:".length).trim().split(/\s+/).filter(Boolean) : [];
}

function header(icons: Picked[], command: string): string {
  const sources = [...new Set(icons.map((i) => i.source))].sort().join(", ");
  return [
    `// Generated by \`nsh-icons ${command}\` from ${sources}. Change the list with the CLI;`,
    "// it rewrites this file. Each icon keeps its set's license.",
    `// nsh-icons: ${icons.map((i) => i.id).join(" ")}`,
  ].join("\n");
}

/** A Rust string literal: escapes and non-ASCII as `\u{..}`. */
export function rustString(value: string): string {
  let out = '"';
  for (const ch of value) {
    const code = ch.codePointAt(0)!;
    if (ch === '"' || ch === "\\") out += `\\${ch}`;
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

function f32(value: number): string {
  const text = String(Object.is(value, -0) ? 0 : value);
  return text.includes(".") || text.includes("e") ? `${text}_f32` : `${text}.0_f32`;
}

/** The module `nsh-icons add` writes: one export per icon, sorted by id. */
export function iconModule(icons: Picked[], lang: Lang): string {
  const sorted = [...icons].sort((a, b) => (a.id < b.id ? -1 : 1));
  if (lang === "ts") {
    const body = sorted.map(
      (i) =>
        `/** ${i.id}: ${i.setName} (${i.license}) */\nexport const ${tsName(i.set, i.name)}: IconData = ${JSON.stringify({ set: i.set, name: i.name, body: i.body, viewBox: i.viewBox, multicolor: i.multicolor })};`,
    );
    return `${header(sorted, "add")}\nimport type { IconData } from "nsh-icons";\n\n${body.join("\n\n")}\n`;
  }
  const body = sorted.map((i) => {
    const [l, t, w, h] = i.viewBox;
    return `/// ${i.id}: ${i.setName} (${i.license})\npub const ${rustName(i.set, i.name)}: Icon = Icon { set: ${rustString(i.set)}, name: ${rustString(i.name)}, body: ${rustString(i.body)}, view_box: [${f32(l)}, ${f32(t)}, ${f32(w)}, ${f32(h)}], multicolor: ${i.multicolor} };`;
  });
  return `${header(sorted, "add --lang rust")}\nuse nsh_icons::Icon;\n\n${body.join("\n\n")}\n`;
}

/** The first code point the font gives out, in Unicode's private use area. */
export const FIRST_CODEPOINT = 0xe000;

/** Why an icon cannot be a font glyph: a font holds one-color filled outlines. */
export function fontProblem(icon: Picked): string | undefined {
  if (icon.multicolor) return "is multicolor, and a glyph has one color";
  if (/stroke(-width)?="(?!none")[^"]*"/.test(icon.body) || /stroke-width/.test(icon.body)) {
    return "is drawn with strokes, and a glyph holds filled outlines only";
  }
  return undefined;
}

/** The TrueType font for `icons`, in id order, from U+E000 up. */
export async function buildFont(icons: Picked[], family: string): Promise<Uint8Array> {
  const sorted = [...icons].sort((a, b) => (a.id < b.id ? -1 : 1));
  const problems = sorted.flatMap((i) => {
    const problem = fontProblem(i);
    return problem ? [`${i.id} ${problem}`] : [];
  });
  if (problems.length) throw new Error(`${problems.join("\n")}\nUse the SVG form for these (nsh-icons add).`);
  // Loaded here so commands that write no font run without the font libraries.
  const { default: svg2ttf } = await import("svg2ttf");
  const { SVGIcons2SVGFontStream } = await import("svgicons2svgfont");
  const svgFont = await new Promise<string>((done, fail) => {
    // The stream emits strings or buffers depending on its mode.
    const chunks: string[] = [];
    const stream = new SVGIcons2SVGFontStream({ fontName: family, fontHeight: 1000, normalize: true, centerHorizontally: true, log: () => {} } as never);
    stream.on("data", (chunk: string | Buffer) => chunks.push(typeof chunk === "string" ? chunk : chunk.toString("utf8")));
    stream.on("end", () => done(chunks.join("")));
    stream.on("error", fail);
    sorted.forEach((icon, at) => {
      const glyph = Readable.from([svgMarkup(icon)]) as Readable & { metadata: unknown };
      glyph.metadata = { name: tsName(icon.set, icon.name), unicode: [String.fromCodePoint(FIRST_CODEPOINT + at)] };
      stream.write(glyph);
    });
    stream.end();
  });
  // A fixed timestamp keeps the font's bytes the same for the same icons.
  const ttf = svg2ttf(svgFont, { ts: 0, description: `nsh-icons: ${sorted.map((i) => i.id).join(" ")}` });
  return new Uint8Array(ttf.buffer);
}

/** The glyph map `nsh-icons font` writes beside the font. */
export function glyphModule(icons: Picked[], family: string, fontPath: string, lang: Lang): string {
  const sorted = [...icons].sort((a, b) => (a.id < b.id ? -1 : 1));
  if (lang === "ts") {
    const body = sorted.map(
      (i, at) => `/** ${i.id}: ${i.setName} (${i.license}) */\nexport const ${tsName(i.set, i.name)}: GlyphData = { family, codepoint: 0x${(FIRST_CODEPOINT + at).toString(16)} };`,
    );
    return `${header(sorted, "font")}\nimport type { GlyphData } from "nsh-icons";\n// Importing the font registers it before the first frame.\nimport family from ${JSON.stringify(fontPath)};\n\n${body.join("\n\n")}\n`;
  }
  const body = sorted.map(
    (i, at) => `/// ${i.id}: ${i.setName} (${i.license})\npub const ${rustName(i.set, i.name)}: Glyph = Glyph { family: FAMILY, codepoint: '\\u{${(FIRST_CODEPOINT + at).toString(16)}}' };`,
  );
  return `${header(sorted, "font --lang rust")}\nuse nsh_icons::Glyph;\n\n/// Register it with \`Root::font(FONT)\` before the first frame.\npub const FONT: &[u8] = include_bytes!(${rustString(fontPath)});\npub const FAMILY: &str = ${rustString(family)};\n\n${body.join("\n\n")}\n`;
}
